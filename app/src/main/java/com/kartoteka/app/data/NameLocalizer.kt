        "Данило" to "Даниил", "Матвій" to "Матвей", "Тимофій" to "Тимофей", "Семен" to "Семён", "Леонід" to "Леонид",
        "Аркадій" to "Аркадий", "Борис" to "Борис", "Едуард" to "Эдуард", "Ілларіон" to "Илларион", "Яків" to "Яков",

    )
    private val ukToRu = pairs.associate { it.first.lowercase() to it.second }
    private val ruToUk = pairs.associate { it.second.lowercase() to it.first }.toMutableMap().apply {
        put("анна", "Анна"); put("наталия", "Наталія"); put("илья", "Ілля"); put("даниил", "Данило")
    }

    fun firstName(name: String, lang: MessageLang): String {
        val n = name.trim()
        if (n.isEmpty() || n.none { it in 'Ѐ'..'ӿ' }) return n
        val key = n.lowercase().replace('’', '\'').replace('ʼ', '\'')
        return when (lang) {
            MessageLang.RU -> ukToRu[key] ?: n
            MessageLang.UK -> ruToUk[key] ?: n
            MessageLang.EN -> latin(ruToUk[key] ?: n)
        }.let { keepCase(n, it) }
    }

    private fun keepCase(src: String, out: String) =
        if (src.firstOrNull()?.isUpperCase() == true) out.replaceFirstChar { it.uppercase() } else out

    /** Транслитерация в латиницу (украинская официальная + русские буквы). */
    fun latin(s: String): String {
        val sb = StringBuilder()
        s.forEachIndexed { i, ch ->
            val lower = ch.lowercase()[0]
            val first = i == 0 || !s[i - 1].isLetter()
            val r = when (lower) {
                'а' -> "a"; 'б' -> "b"; 'в' -> "v"; 'г' -> "h"; 'ґ' -> "g"; 'д' -> "d"; 'е' -> "e"; 'є' -> if (first) "ye" else "ie"
                'ж' -> "zh"; 'з' -> "z"; 'и' -> "y"; 'і' -> "i"; 'ї' -> if (first) "yi" else "i"; 'й' -> if (first) "y" else "i"
                'к' -> "k"; 'л' -> "l"; 'м' -> "m"; 'н' -> "n"; 'о' -> "o"; 'п' -> "p"; 'р' -> "r"; 'с' -> "s"; 'т' -> "t"
                'у' -> "u"; 'ф' -> "f"; 'х' -> "kh"; 'ц' -> "ts"; 'ч' -> "ch"; 'ш' -> "sh"; 'щ' -> "shch"
                'ю' -> if (first) "yu" else "iu"; 'я' -> if (first) "ya" else "ia"; 'ь', '\'', '’', 'ʼ', 'ъ' -> ""
                'ы' -> "y"; 'э' -> "e"; 'ё' -> "yo"
                else -> lower.toString()
            }
            sb.append(if (ch.isUpperCase()) r.replaceFirstChar { it.uppercase() } else r)
        }
        return sb.toString()
    }

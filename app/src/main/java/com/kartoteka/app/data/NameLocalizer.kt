/**
 * Имя человека на языке сообщения: «Ілля» в русском тексте — «Илья», в английском — «Illia».
 * Для украинского ↔ русского — словарь распространённых имён (их формы не выводятся по буквам);
 * для английского — транслитерация (украинская официальная / русская по буквам). Незнакомое имя не трогаем.
